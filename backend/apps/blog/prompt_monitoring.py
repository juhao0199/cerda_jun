def prompt_row(p, latest=None):
    latest = latest or {}
    now = timezone.now()
    return {'id':str(p.pk),'question':p.question,'language':p.language,'market':p.market,'intent':p.intent,
            'engines':p.engines,'cadenceDays':p.cadence_days,'active':p.active,'version':str(p.version),
            'checks':[{'engine':e,'lastObserved':latest[e].isoformat() if e in latest else None,
                       'due':p.active and (e not in latest or latest[e]+timedelta(days=p.cadence_days)<=now)} for e in p.engines]}


def record_row(r):
    return {'id':str(r.pk),'promptId':str(r.prompt_id),'engine':r.engine,'observedAt':r.observed_at.isoformat(),
            'recordedAt':r.created_at.isoformat(),'context':r.context,'answer':r.answer,'brand':r.brand,
            'citation':r.citation,'sources':r.sources,'evidence':r.evidence}


def metrics(qs):
    fields = {f'{name}_{outcome}':Count('id',filter=Q(**{name:outcome})) for name in ('answer','brand','citation') for outcome in OUTCOMES}
    return qs.aggregate(total=Count('id'),**fields)


def cited_urls(qs):
    # Aggregate only confirmed, reported owned sources across the entire selected sample.
    # The subquery is generated by Django; all user filter values are bound parameters.
    sql, params = qs.filter(citation='present').order_by().values('id').query.sql_with_params()
    with connection.cursor() as cur:
        cur.execute("""SELECT source.value->>'url', COUNT(DISTINCT m.id)
            FROM blog_promptmeasurement AS m
            CROSS JOIN LATERAL jsonb_array_elements(m.sources) AS source(value)
            WHERE m.id IN (""" + sql + """) AND source.value->>'owned' = 'true'
            GROUP BY source.value->>'url' ORDER BY COUNT(DISTINCT m.id) DESC, source.value->>'url' ASC LIMIT 20""", params)
        return [{'url':url,'checks':count} for url,count in cur.fetchall()]


def valid_id(s):
    return isinstance(s,str) and s.isascii() and s.isdigit() and 0<len(s)<=19 and 0<int(s)<2**63


@require_GET
@require_role('owner','staff')
def listing(request):
    parsed = pagination(request, {'q','page','status'})
    status = request.GET.get('status','active')
    if parsed is None or status not in ('active','archived','all'): return fail('Invalid filters.',400)
    page,q = parsed
    qs = TrackedPrompt.objects.all()
    if status != 'all': qs=qs.filter(active=status=='active')
    if q: qs=qs.filter(Q(question__icontains=q)|Q(market__icontains=q)|Q(language__icontains=q))
    rows=list(qs.order_by('-created_at','-id')[(page-1)*20:page*20+1])
    latest={}
    for x in PromptMeasurement.objects.filter(prompt_id__in=[p.pk for p in rows[:20]]).values('prompt_id','engine').annotate(last=Max('observed_at')):
        latest.setdefault(x['prompt_id'],{})[x['engine']]=x['last']
    recent=PromptMeasurement.objects.filter(observed_at__gte=timezone.now()-timedelta(days=30))
    return JsonResponse({'results':[prompt_row(p,latest.get(p.pk)) for p in rows[:20]],'hasMore':len(rows)>20,
                         'activeCount':TrackedPrompt.objects.filter(active=True).count(),'metrics':metrics(recent)})


@json_post
@require_role('owner','staff')
def create(request,data):
    try:
        if set(data)!={'question','language','market','intent','engines','cadenceDays'} or not all(isinstance(v,str) for v in data.values()): raise ValueError('Invalid prompt.')
        question=text(data['question'],500,1);language=text(data['language'],40,1);market=text(data['market'],80,1)
        engines=data['engines'].split(',');intent=data['intent'];cadence=data['cadenceDays']
        if not engines or len(engines)!=len(set(engines)) or any(e not in ENGINES for e in engines) or intent not in INTENTS or cadence not in ('7','14','30'): raise ValueError('Invalid monitoring settings.')
        key=prompt_key(question,language,market,engines)
    except (ValueError,UnicodeError) as e: return fail(str(e),400)
    try:
        with transaction.atomic():
            if locked_role(request) not in ('owner','staff'): return fail('Access denied.',403)
            p=TrackedPrompt.objects.create(question=question,language=language,market=market,intent=intent,engines=engines,cadence_days=int(cadence),key=key,actor_id=request.user.pk)
            audit('blog.prompt.create',request.user,subject=str(p.pk))
            return JsonResponse(prompt_row(p),status=201)
    except IntegrityError: return fail('This question and test context already exist. Restore the archived prompt if needed.',409)


@json_post
@require_role('owner')
def change(request,data):
    if set(data)!={'id','version','action'} or not valid_id(data['id']) or not valid_id(data['version']) or data['action'] not in ('archive','restore'): return fail('Invalid prompt change.',400)
    with transaction.atomic():
        if locked_role(request)!='owner': return fail('Access denied.',403)
        p=TrackedPrompt.objects.select_for_update().filter(pk=data['id']).first()
        if not p: return fail('Prompt not found.',404)
        if str(p.version)!=data['version']: return fail('Prompt changed. Refresh before retrying.',409)
        active=data['action']=='restore'
        if p.active!=active:
            p.active=active;p.version+=1;p.save(update_fields=['active','version'])
            audit('blog.prompt.'+data['action'],request.user,subject=str(p.pk))
        return JsonResponse({'id':str(p.pk),'active':p.active,'version':str(p.version)})


@require_GET
@require_role('owner','staff')
def history(request):
    parsed=pagination(request,{'id','engine','page','days'})
    pid=request.GET.get('id','');engine=request.GET.get('engine','');days=request.GET.get('days','30')
    if parsed is None or not valid_id(pid) or engine not in ('',*ENGINES) or days not in ('30','90','all'): return fail('Invalid history filters.',400)
    p=TrackedPrompt.objects.filter(pk=pid).first()
    if not p: return fail('Prompt not found.',404)
    qs=p.measurements.all()
    if engine: qs=qs.filter(engine=engine)
    if days!='all': qs=qs.filter(observed_at__gte=timezone.now()-timedelta(days=int(days)))
    page,_=parsed;rows=list(qs.order_by('-observed_at','-id')[(page-1)*20:page*20+1])
    latest={x['engine']:x['last'] for x in p.measurements.values('engine').annotate(last=Max('observed_at'))}
    return JsonResponse({'prompt':prompt_row(p,latest),'results':[record_row(r) for r in rows[:20]],'hasMore':len(rows)>20,'metrics':metrics(qs),
                         'citations':cited_urls(qs),'engines':[{'engine':e,**metrics(qs.filter(engine=e))} for e in p.engines if not engine or e==engine]})


@json_post
@require_role('owner','staff')
def record(request,data):
    try:
        if set(data)!={'id','requestId','engine','observedAt','context','answer','brand','citation','sources','evidence'} or not all(isinstance(v,str) for v in data.values()) or not valid_id(data['id']): raise ValueError('Invalid observation.')
        rid=uuid.UUID(data['requestId']);engine=data['engine']
        if rid.version!=4 or engine not in ENGINES or any(data[k] not in OUTCOMES for k in ('answer','brand','citation')): raise ValueError('Invalid measurement choice.')
        values={'engine':engine,'observed_at':observed_time(data['observedAt'],timezone.now()),'context':text(data['context'],250,1),
                'answer':data['answer'],'brand':data['brand'],'citation':data['citation'],'sources':sources(data['sources'],data['citation']),
                'evidence':text(data['evidence'],1500,1)}
    except (ValueError,UnicodeError) as e: return fail(str(e),400)
    with transaction.atomic():
        if locked_role(request) not in ('owner','staff'): return fail('Access denied.',403)
        p=TrackedPrompt.objects.select_for_update().filter(pk=data['id']).first()
        if not p: return fail('Prompt not found.',404)
        previous=PromptMeasurement.objects.filter(pk=rid).first()
        if previous:
            if previous.prompt_id==p.pk and previous.actor_id==request.user.pk and all(getattr(previous,k)==v for k,v in values.items()): return JsonResponse(record_row(previous))
            return fail('Observation ID already used.',409)
        if not p.active or engine not in p.engines: return fail('Prompt is archived or engine is not tracked.',409)
        try:
            with transaction.atomic(): obj=PromptMeasurement.objects.create(id=rid,prompt=p,actor_id=request.user.pk,**values)
        except IntegrityError: return fail('Observation ID already used.',409)
        audit('blog.prompt.record',request.user,subject=str(obj.pk))
        return JsonResponse(record_row(obj),status=201)
